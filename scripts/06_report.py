"""Stage G: leaderboard per stratum, error-vs-length / error-vs-beam curves, reliable length range."""
import os, json, numpy as np, pandas as pd
import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
C = json.load(open("config.json"))
LB = pd.read_csv("results/leaderboard.tsv", sep="\t"); SCL = pd.read_csv("results/scaling.tsv", sep="\t")
B = pd.read_csv("results/bias_per_rna.tsv", sep="\t"); BS = pd.read_csv("results/bias_summary.tsv", sep="\t")

fig, ax = plt.subplots(1, 2, figsize=(11, 4.2))
for tool, g in B.groupby("tool"):
    g = g.sort_values("length"); ax[0].semilogx(g.length, g.mad_unpaired, ".", ms=3, label=tool)
ax[0].axhline(C["mad_tolerance"], ls="--", c="k", lw=.8); ax[0].set(xlabel="length (nt)", ylabel="MAD p(unpaired) vs exact")
ax[0].legend(fontsize=6)
for kind in ("linearpartition", "linearsampling"):
    g = B[B.tool.str.startswith(kind)].copy(); g["beam"] = g.tool.str.extract(r"_b(-?\d+)").astype(int)[0].replace(0, 10**4)
    m = g.groupby("beam").mad_unpaired.agg(["mean", lambda x: np.percentile(x, 95)])
    ax[1].semilogx(m.index, m.iloc[:, 1], "o-", label=f"{kind} p95"); ax[1].semilogx(m.index, m["mean"], "x--", label=f"{kind} mean")
ax[1].set(xlabel="beam (10^4 = infinite/0)", ylabel="MAD p(unpaired)"); ax[1].legend(fontsize=7)
fig.tight_layout(); fig.savefig("results/fig_bias.png", dpi=150)

# reliable length: largest length L such that every RNA <= L has MAD below tolerance, per tool
rel = []
for tool, g in B.groupby("tool"):
    g = g.sort_values("length"); bad = g[g.mad_unpaired > C["mad_tolerance"]]
    first_bad = bad.length.min() if len(bad) else None
    ok = g[g.length < first_bad] if first_bad else g
    rel.append(dict(tool=tool, n=len(g), p95_mad_unpaired=np.percentile(g.mad_unpaired, 95), max_mad_unpaired=g.mad_unpaired.max(),
                    reliable_up_to_nt=int(ok.length.max()) if len(ok) else 0, first_failure_nt=first_bad, max_tested_nt=int(g.length.max())))
REL = pd.DataFrame(rel); REL.to_csv("results/reliable_length.tsv", sep="\t", index=False, float_format="%.4f")

md = lambda d: d.to_markdown(index=False, floatfmt=".3f")
with open("results/REPORT.md", "w") as f:
    f.write("# Gap 4 benchmark + Gap 3a bias audit: results\n\n")
    f.write("Auto-generated by scripts/06_report.py. Scores on held-out RNAs only. Spearman/AUC = p(unpaired) vs normalised reactivity; "
            "95% CI = bootstrap over RNAs. bp F1/MCC = pairs with p>0.5 vs reference dot-bracket.\n\n")
    f.write("## Leaderboard per length stratum\n\n" + md(LB) + "\n\n")
    f.write("## Runtime and memory scaling (log-log slope vs length)\n\n" + md(SCL) + "\n\n![scaling](fig_scaling.png)\n\n")
    f.write(f"## Gap 3a: linear-time vs exact (tolerance MAD p(unpaired) <= {C['mad_tolerance']})\n\n" + md(BS) + "\n\n")
    f.write("### Error bound and reliable length range\n\n" + md(REL) + "\n\n![bias](fig_bias.png)\n")
print(REL.to_string(index=False))
